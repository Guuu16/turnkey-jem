// Money is stored and transported as integer cents. Formatting happens once,
// with an explicit locale, so server and client render identical strings.
export function formatMoney(cents: number, currency: string): string {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(cents / 100);
}
